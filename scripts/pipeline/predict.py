def _log_prediction_crash_summary(
    exp_logger: ExperimentLogger,
    exc: BaseException,
    *,
    saved_gt_names: set[str],
    saved_ranking_gt_names: set[str],
) -> None:
    """Log crash-summary metadata for saved GT artifacts."""
    saved_gt = sorted(saved_gt_names)
    saved_ranking_gt = sorted(saved_ranking_gt_names)
    logger.warning(
        "Prediction interrupted. GT predictions saved: %s. Ranking GT predictions saved: %s",
        saved_gt or "none",
        saved_ranking_gt or "none",
    )
    exp_logger.log_event(
        "crash_summary",
        {
            "saved_gt_names": saved_gt,
            "saved_ranking_gt_names": saved_ranking_gt,
            "reason": str(exc),
        },
    )


def _handle_pipeline_exception(
    exc: BaseException | None,
    *,
    exp_logger: ExperimentLogger,
    log_path: Path,
    output_dir: Path,
    saved_gt_names: set[str],
    saved_ranking_gt_names: set[str],
) -> bool:
    """Save partial artifacts then decide whether to abort gracefully.

    Always attempts the crash-summary event and log-save (both wrapped in
    their own ``try/except`` so a failure in one does not block the other).
    Returns ``True`` when the caller should exit cleanly (quota exhausted
    after all retries — partial results on disk are the resume point);
    returns ``False`` when the caller should re-raise the original exception.
    """
    try:
        _log_prediction_crash_summary(
            exp_logger,
            exc if exc is not None else RuntimeError("prediction interrupted"),
            saved_gt_names=saved_gt_names,
            saved_ranking_gt_names=saved_ranking_gt_names,
        )
    except Exception:
        logger.exception("Failed to log crash summary")
    try:
        exp_logger.save_logs(log_path)
        logger.info(
            "Logs saved on crash to %s (%d records)",
            log_path,
            len(exp_logger.records),
        )
    except Exception:
        logger.exception("Failed to save logs on crash")
    if exc is not None and is_quota_exhausted_error(exc):
        logger.warning(
            "Quota exhausted after all retries. Completed GT groups and "
            "shard-flushed rollouts under %s are preserved. Re-run the "
            "same command to resume from the persisted state. Error: %s",
            output_dir,
            exc,
        )
        return True
    return False


def _build_scripted_policy_metadata(
    *,
    policy_name: str,
    make_kwargs: dict[str, Any] | None,
    step_penalty: float | None = None,
) -> dict[str, Any]:
    """Build runtime metadata passed into scripted policies."""
    del policy_name
    metadata: dict[str, Any] = {}
    if make_kwargs:
        # When the env uses a map cycler (num_maps > 1), the map varies per
        # trajectory, so don't pin map_name/desc — the policy must parse the
        # current grid from the state text on every call.
        dynamic_map = int(make_kwargs.get("num_maps") or 0) > 1
        for key in ("map_name", "is_slippery", "success_rate"):
            if key == "map_name" and dynamic_map:
                continue
            if key in make_kwargs:
                metadata[key] = make_kwargs[key]
        if (
            not dynamic_map
            and "desc" in make_kwargs
            and make_kwargs["desc"] is not None
        ):
            metadata["desc"] = tuple(str(row) for row in make_kwargs["desc"])
        if (
            "reward_schedule" in make_kwargs
            and make_kwargs["reward_schedule"] is not None
        ):
            metadata["reward_schedule"] = tuple(make_kwargs["reward_schedule"])
    if step_penalty is not None:
        metadata["step_penalty"] = float(step_penalty)
    return metadata


def _catalog_root_for_config(config_path: Path) -> Path:
    """Resolve the catalog root that owns a prediction config.

    Generated prediction configs live at
    ``<catalog_root>/configs/<subtype>/<env>/<file>.yaml``, alongside the
    catalog's ``catalog.py``. A config's ``predictions_dir`` (e.g.
    ``data/predictions/<env>/<dir>``) is catalog-relative, so it joins this
    root. Walk up to the directory containing ``catalog.py``; if none is found
    (an ad-hoc config outside any catalog) fall back to the current working
    directory, preserving the historical CWD-relative behaviour.
    """
    for parent in config_path.resolve().parents:
        if (parent / "catalog.py").is_file():
            return parent
    return Path.cwd()


def _timestamped_log_filename(prefix: str) -> str:
    ts = datetime.now().astimezone().strftime("%Y%m%d_%H%M%S")
    return f"{prefix}_{ts}.jsonl"


def _split_eval_method_configs(
    configs: list[EvalMethodConfig],
) -> tuple[list[EvalMethodConfig], list[EvalMethodConfig]]:
    """Split eval method configs into regular and ranking lists."""
    regular = [mc for mc in configs if mc.type not in _RANKING_EVAL_METHOD_TYPES]
    ranking = [mc for mc in configs if mc.type in _RANKING_EVAL_METHOD_TYPES]
    return regular, ranking


def _should_run_ranking_predictions(
    *,
    ranking_points: list[Any],
    ranking_eval_configs: list[Any],
    estimation_configs: list[Any],
) -> bool:
    """Return whether the ranking prediction pipeline should run."""
    has_ranking_gt = any(
        getattr(est_config, "assumption", None) != SignalType.SHAPED_REWARD
        for est_config in estimation_configs
    )
    return bool(ranking_points) and bool(ranking_eval_configs or has_ranking_gt)


