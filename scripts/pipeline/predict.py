def _flatten_rankings_to_ranks(
    *,
    rankings: list[list[int] | None],
    ranking_points: list[RankingPoint],
) -> list[float]:
    """Convert per-point orderings into flattened per-candidate ranks."""
    if len(rankings) != len(ranking_points):
        raise ValueError(
            "rankings and ranking_points must have the same length, "
            f"got {len(rankings)} and {len(ranking_points)}"
        )

    flat_ranks: list[float] = []
    for ordering, point in zip(rankings, ranking_points, strict=True):
        k = len(point.candidates)
        if ordering is None:
            flat_ranks.extend([float("nan")] * k)
            continue

        ranks = [0] * k
        for position, action_num in enumerate(ordering, 1):
            ranks[action_num - 1] = position
        flat_ranks.extend(float(rank) for rank in ranks)

    return flat_ranks


def _build_gt_history_fn(
    context: MethodContext,
    max_history_turns: int | None = None,
) -> Any:
    """Build the GT history truncation function from environment context."""
    history_fn = None
    if (
        context.min_action_chars is not None
        or context.min_observation_chars is not None
    ):
        from qval.benchmark import content_truncated_history

        history_fn = content_truncated_history(
            min_action_chars=context.min_action_chars,
            min_observation_chars=context.min_observation_chars,
        )
    if max_history_turns is not None:
        from qval.benchmark import truncated_last_n_history

        history_fn = truncated_last_n_history(max_history_turns, inner=history_fn)
    return history_fn


def _normalize_descriptor(value: Any) -> Any:
    if dataclasses.is_dataclass(value):
        return _normalize_descriptor(dataclasses.asdict(value))
    if isinstance(value, dict):
        return {str(key): _normalize_descriptor(inner) for key, inner in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_normalize_descriptor(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if hasattr(value, "__dict__") and vars(value):
        return {
            "__class__": f"{value.__class__.__module__}.{value.__class__.__qualname__}",
            "fields": _normalize_descriptor(vars(value)),
        }
    if callable(value):
        module = getattr(value, "__module__", None) or ""
        qualname = (
            getattr(value, "__qualname__", None)
            or getattr(value, "__name__", None)
            or ""
        )
        return f"{module}.{qualname}" if module else qualname
    return repr(value)


def _rollout_persistence_make_kwargs(
    adapter: str,
    make_kwargs: dict[str, Any] | None,
) -> dict[str, Any] | None:
    if make_kwargs is None:
        return None
    normalized = dict(make_kwargs)
    if adapter == "harbor":
        for key in (
            "environment_type",
            "podman_command",
            "apptainer_command",
            "trials_dir",
            "sif_cache_dir",
        ):
            normalized.pop(key, None)
    if adapter == "open_apps":
        # Runtime timeout knob: doesn't affect rollout content, so it
        # shouldn't invalidate the descriptor hash on bumps.
        normalized.pop("browsergym_call_timeout", None)
    return normalized


