def _ranking_point_keys(ranking_points: list[RankingPoint]) -> list[tuple[int, ...]]:
    keys: list[tuple[int, ...]] = []
    for point in ranking_points:
        for candidate_index, _candidate in enumerate(point.candidates):
            keys.append((point.trajectory_index, point.step_index, candidate_index))
    return keys


def _build_eval_q_lookup(
    gt_values: dict[str, list[float]],
    estimations: Sequence[Any],
    points: list[EvaluationPoint],
) -> dict[str, dict[tuple[int, int], float]]:
    """Map est_config.name -> {(traj_idx, step_idx): Q-value} for Q_VALUE configs."""
    lookup: dict[str, dict[tuple[int, int], float]] = {}
    for est_config in estimations:
        if est_config.assumption != SignalType.Q_VALUE:
            continue
        values = gt_values.get(est_config.name)
        if values is None:
            continue
        lookup[est_config.name] = {
            (p.trajectory_index, p.step_index): v for p, v in zip(points, values)
        }
    return lookup


def _validate_prediction_dataset(dataset: Any) -> None:
    """Reject datasets that still contain failed trajectories or bad indices."""
    trajectory_results = getattr(dataset, "trajectory_results", None)
    if not trajectory_results:
        return

    for result in trajectory_results:
        error = getattr(result, "metadata", {}).get("error")
        if error:
            raise ValueError(
                "Dataset contains failed trajectories in trajectory_results. "
                "Regenerate the dataset with failed trajectories dropped before prediction."
            )

    num_trajectories = len(trajectory_results)
    for label, points in (
        ("evaluation", getattr(dataset, "evaluation_points", [])),
        ("ranking", getattr(dataset, "ranking_points", [])),
    ):
        for point in points:
            if not (0 <= point.trajectory_index < num_trajectories):
                raise ValueError(
                    f"Dataset contains {label} point with trajectory_index="
                    f"{point.trajectory_index} outside valid range "
                    f"[0, {num_trajectories})"
                )


def _validate_gvl_dataset_requirements(
    dataset: Any,
    eval_method_configs: Sequence[EvalMethodConfig],
) -> None:
    """Fail fast when GVL is requested without stored trajectories."""
    if not any(mc.type == "llm_direct_gvl" for mc in eval_method_configs):
        return

    trajectory_results = getattr(dataset, "trajectory_results", None)
    if trajectory_results is None:
        raise ValueError(
            "llm_direct_gvl requires dataset trajectory_results. "
            "Saved-trajectory-JSON fallback is not implemented yet."
        )

    num_trajectories = len(trajectory_results)
    for point in getattr(dataset, "evaluation_points", ()):
        if not (0 <= point.trajectory_index < num_trajectories):
            raise ValueError(
                "llm_direct_gvl requires valid trajectory indices in evaluation_points: "
                f"trajectory_index={point.trajectory_index} outside [0, {num_trajectories})"
            )
        transitions = getattr(
            getattr(trajectory_results[point.trajectory_index], "trajectory", None),
            "transitions",
            None,
        )
        if transitions is None:
            raise ValueError(
                "llm_direct_gvl requires trajectory_results with trajectory.transitions"
            )
        if not (0 <= point.step_index < len(transitions)):
            raise ValueError(
                "llm_direct_gvl requires step_index values aligned with stored trajectories: "
                f"trajectory_index={point.trajectory_index}, step_index={point.step_index}, "
                f"num_steps={len(transitions)}"
            )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Step 2: Generate GT and/or eval method predictions"
    )
    parser.add_argument("--dataset", default=None, help="Path to dataset pickle")
    parser.add_argument(
        "--config", required=True, help="Path to prediction YAML config"
    )
    parser.add_argument(
        "--output-dir", default=None, help="Output directory for prediction JSONs"
    )
    parser.add_argument(
        "--tensor-parallel-size",
        type=int,
        default=None,
        help="Override tensor_parallel_size for all vLLM backends (e.g. from SLURM GPU count)",
    )
    parser.add_argument(
        "--max-aborted-points",
        type=float,
        default=None,
        help="Abort if the fraction of backend-aborted points exceeds this threshold (default: 0.1)",
    )
    parser.add_argument(
        "--max-eval-points",
        type=int,
        default=None,
        help="Use at most this many evaluation points from the dataset (first N)",
    )

    args = parser.parse_args()

    from qval.error_handling import install_sigfpe_handler

    install_sigfpe_handler()

    # 1. Load dataset and config
    config_path = Path(args.config)
    with config_path.open() as f:
        raw_config = yaml.safe_load(f) or {}
    config = PipelinePredictionConfig.from_dict(raw_config)
    if args.max_aborted_points is not None:
        config = dataclasses.replace(config, max_aborted_points=args.max_aborted_points)
    if args.max_eval_points is not None:
        config = dataclasses.replace(config, max_eval_points=args.max_eval_points)
    backends_config = BackendsRegistryConfig.from_yaml(config.backends_config_path)

    dataset_path = args.dataset or config.dataset_path
    if not dataset_path:
        raise ValueError("dataset_path is required (set in config or CLI)")
    resolved_dataset_path = resolve_dataset_path(dataset_path)
    logger.info("Loading dataset from %s", resolved_dataset_path)
    dataset = load_dataset(resolved_dataset_path)
    _validate_prediction_dataset(dataset)
    _validate_gvl_dataset_requirements(dataset, config.eval_methods or ())
    logger.info(
        "Loaded: %d eval points, %d trajectory returns%s",
        len(dataset.evaluation_points),
        len(dataset.trajectory_returns),
        " (multimodal: includes images)"
        if getattr(dataset, "has_images", False)
        else " (text-only)",
    )

    if not dataset.evaluation_points:
        logger.error("No evaluation points in dataset")
        return

    # ``--output-dir`` is a CWD-relative CLI override; a config ``predictions_dir``
    # is catalog-relative (joins the catalog root that owns this config).
    if args.output_dir:
        output_dir = Path(args.output_dir)
    elif config.predictions_dir:
        output_dir = _catalog_root_for_config(config_path) / config.predictions_dir
    else:
        raise ValueError("predictions_dir is required (set in config or CLI)")
    log_path = output_dir / _timestamped_log_filename("predict.logs")
    output_dir.mkdir(parents=True, exist_ok=True)

    # 2. Build backends
    exp_logger = ExperimentLogger()
    exp_logger.attach_jsonl_sink(log_path)
    if resolved_dataset_path.exists():
        dataset_fingerprint = dataset_fingerprint_for_file(resolved_dataset_path)
    else:
        logger.warning(
            "Dataset file %s is unavailable on disk; hashing loaded dataset object for MC rollout persistence",
            resolved_dataset_path,
        )
        dataset_fingerprint = dataset_fingerprint_for_object(
            dataset,
            path_hint=str(resolved_dataset_path),
        )
    persistence_config = config.mc_rollout_persistence
    rollout_store_root = (
        Path(persistence_config.dir)
        if persistence_config.dir is not None
        else output_dir / "rollouts"
    )

    # 4. Load context
    prediction_config = config.prediction
    context_name = (
        prediction_config.context_name
        or dataset.metadata.get("context_name")
        or dataset.metadata.get("env_name", "unknown")
    )
    contexts_dir = prediction_config.contexts_dir or dataset.metadata.get(
        "contexts_dir", "shared/configs/environments/"
    )
    # signal_type on context is overridden per eval method below;
    # use STATE_VALUE as placeholder for environment-level context loading.
    context = load_context(
        env_name=context_name,
        signal_type=SignalType.STATE_VALUE,
        contexts_dir=contexts_dir,
    )
    # EnvironmentContext carries rendering flags that MethodContext
    # deliberately does not (e.g. inject_task_text_in_prompts). Keep it
    # in scope so Method constructors can forward env-side decisions.
    env_context = load_environment_context(
        env_name=context_name,
        contexts_dir=contexts_dir,
    )
    from qval.system_prompts import SCHEME_INSTRUCTIONS

    actor_scheme = getattr(context, "prompting_scheme", None) or "answer_tags"
    actor_format_reminder = SCHEME_INSTRUCTIONS.get(actor_scheme)

    # Set discount factor on context
    context = dataclasses.replace(context, discount_factor=config.discount_factor)

    # Augment context with runtime environment notes from metadata
    env_notes: list[str] = []
    dataset_max_steps = resolve_effective_max_steps(
        dataset.metadata.get("max_steps"),
        dataset.metadata.get("make_kwargs"),
    )
    if dataset_max_steps is not None:
        env_notes.append(f"The episode step limit is {dataset_max_steps}.")
    if env_notes:
        context = dataclasses.replace(context, environment_notes=env_notes)

    # Step penalty: use prediction-level config (not dataset metadata)
    step_penalty = config.step_penalty

    start = time.time()

    default_trials_dir = os.environ.get("VB_TRIALS_DIR", "trials")
    resource_watch_dirs = [default_trials_dir]

    points = dataset.evaluation_points
    if config.max_eval_points is not None:
        total = len(points)
        points = points[: config.max_eval_points]
        logger.info("Using first %d of %d eval points", len(points), total)

    # Shared backend cache: reuse instances that share the same model/construction
    # parameters, even if their sampling settings differ.
    backend_cache: dict[Any, Any] = {}

    tp_override = args.tensor_parallel_size

    def get_backend(backend_config: Any) -> Any:
        """Return a (cached) LoggingBackend for the given BackendConfig.

        The cache key excludes per-request-only fields (``sampling`` always,
        and ``enable_thinking`` for backend types that apply it per request)
        so backends sharing all construction parameters are reused. See
        ``backend_cache_key``.
        """
        key = backend_cache_key(backend_config)
        if key not in backend_cache:
            chat_tmpl_kwargs = chat_template_kwargs_from_config(backend_config)
            raw = create_backend_from_config(
                backend_config,
                chat_template_kwargs=chat_tmpl_kwargs,
                tensor_parallel_size_override=tp_override,
            )
            attach_backend_logging_metadata(raw, backend_config)
            quota_wrapped = wrap_with_quota_retry(
                raw, policy=backend_config.quota_retry_policy
            )
            logged = LoggingBackend(quota_wrapped, exp_logger)
            backend_cache[key] = wrap_with_second_elicitation(logged)
            logger.info(
                "Created backend: %s (%s)", backend_config.model, backend_config.type
            )
        else:
            logger.info(
                "Reusing backend: %s (%s)", backend_config.model, backend_config.type
            )
        return backend_cache[key]

    def get_scripted_policy(
        name: str,
        make_kwargs: dict[str, Any] | None,
        step_penalty: float | None,
    ) -> tuple[ScriptedBackend, str]:
        policy_config = get_policy(name)
        metadata = dict(policy_config.metadata)
        metadata.update(
            _build_scripted_policy_metadata(
                policy_name=name,
                make_kwargs=make_kwargs,
                step_penalty=step_penalty,
            )
        )
        backend = ScriptedBackend(
            policy_fn=policy_config.fn,
            metadata=metadata,
        )
        return backend, name

    # ── GT estimation ────────────────────────────────────────────
    has_gt_configs = any(
        e.assumption != SignalType.SHAPED_REWARD for e in config.estimations
    )

    gt_values: dict[str, list[float]] = {}
    gt_env = None
    gt_methods_dict: dict[str, Any] = {}
    raw_returns: dict[str, list[Any]] = {}
    gt_aborted: dict[str, set[int]] = {}
    expected_gt_configs: dict[str, dict[str, Any]] = {}
    gt_compatibility_by_name: dict[str, dict[str, Any]] = {}
    existing_gt: dict[str, Prediction] = {}
    gt_names_to_build: set[str] = set()
    saved_gt_names: set[str] = set()
    saved_ranking_gt_names: set[str] = set()

    replay_cache = None
    if has_gt_configs:
        adapter = (
            prediction_config.adapter
            or context.adapter
            or dataset.metadata.get("adapter", "reasoning_gym")
        )
        env_name = context.env_name or dataset.metadata.get("env_name", "unknown")
        seed = dataset.metadata.get("seed", 42)

        make_kwargs = prediction_config.make_kwargs
        if make_kwargs is None:
            make_kwargs = context.make_kwargs
        if make_kwargs is None and dataset.metadata.get("make_kwargs"):
            make_kwargs = dataset.metadata["make_kwargs"]

        max_steps = resolve_effective_max_steps(context.max_steps, make_kwargs)
        if max_steps is None:
            max_steps = dataset_max_steps

        turn_info = context.turn_info
        if turn_info is None:
            turn_info = dataset.metadata.get("turn_info", False)

        # Compute env_size from metadata
        task_indices = dataset.metadata.get("task_indices")
        num_trajectories = dataset.metadata.get("num_trajectories")
        if task_indices is not None:
            env_size = max(task_indices) + 1
        elif num_trajectories is not None:
            env_size = num_trajectories
        else:
            env_size = 100

        extra_rewards: tuple = ()
        gt_reward_signal_name = context.reward_signal_name
        if step_penalty is not None:
            from llenvs.core.reward import StepPenalty

            extra_rewards = (StepPenalty(penalty=step_penalty),)
            gt_reward_signal_name = None  # sum all signals when penalty active

        # Build GT history function from env context truncation thresholds.
        # Budget-aware truncation is used when a backend exposes context
        # length; uniform truncation is the fallback.
        gt_history_fn = None
        gt_history_fn = _build_gt_history_fn(
            context, max_history_turns=prediction_config.max_history_turns
        )
        gt_environment_descriptor = _build_rollout_environment_descriptor(
            adapter=adapter,
            env_name=env_name,
            max_steps=max_steps,
            make_kwargs=make_kwargs,
            environment_extractor=context.environment_extractor,
            uses_env_factory=adapter in {"harbor", "open_apps"},
            restore_mode=dataset.metadata.get("harbor_state_capture")
            if adapter == "harbor"
            else None,
        )

        ranking_requested = (
            not config.skip_ranking_predictions
            and _should_run_ranking_predictions(
                ranking_points=list(getattr(dataset, "ranking_points", ())),
                ranking_eval_configs=[
                    mc
                    for mc in (config.eval_methods or [])
                    if getattr(mc, "type", None) in _RANKING_EVAL_METHOD_TYPES
                ],
                estimation_configs=list(config.estimations),
            )
        )
        preload_exact_gt_resume = _can_preload_gt_resume_before_env_setup(
            adapter=adapter,
            prediction_config=prediction_config,
            context=context,
        )

        for est_config in config.estimations:
            if est_config.assumption == SignalType.SHAPED_REWARD:
                continue
            expected_gt_configs[est_config.name] = _build_gt_prediction_config(
                assumption=est_config.assumption.name.lower(),
                method=est_config.method,
                aggregation=est_config.aggregation.name.lower(),
                num_rollouts=est_config.num_rollouts,
                backend_name=(
                    None
                    if est_config.policy_name is not None
                    else resolve_backend_name(
                        est_config.backend_name or prediction_config.gt_backend_name,
                        backends_config.backends,
                        backends_config.default_backend,
                    )
                ),
                policy_name=est_config.policy_name,
                step_penalty=step_penalty,
                discount_factor=config.discount_factor,
            )
            if preload_exact_gt_resume:
                gt_compatibility_by_name[est_config.name] = _gt_compatibility_metadata(
                    dataset_fingerprint,
                    points,
                    resume_descriptor=_build_gt_resume_descriptor(
                        est_config=est_config,
                        adapter=adapter,
                        env_name=env_name,
                        max_steps=max_steps,
                        make_kwargs=make_kwargs,
                        context=context,
                        prediction_config=prediction_config,
                        dataset_metadata=dataset.metadata,
                        turn_info=turn_info,
                        gt_environment_descriptor=gt_environment_descriptor,
                        gt_reward_signal_name=gt_reward_signal_name,
                        backends_config=backends_config,
                        step_penalty=step_penalty,
                    ),
                )

        if preload_exact_gt_resume:
            existing_gt = _load_compatible_gt_predictions(
                output_dir / "gt",
                expected_gt_configs,
                num_points=len(points),
                compatibility_metadata_by_name=gt_compatibility_by_name,
            )
            for gt_name, pred in existing_gt.items():
                gt_values[gt_name] = pred.values
                raw_returns[gt_name] = []
                gt_aborted[gt_name] = set()
            saved_gt_names = set(existing_gt.keys())

        gt_names_to_build = _gt_method_names_to_build(
            expected_gt_names=set(expected_gt_configs),
            existing_gt_names=set(existing_gt),
            ranking_requested=ranking_requested,
        )

        env_factory = None
        restore_fn = None
        gt_system_prompt = None
        if gt_names_to_build:
            env, env_system_prompt = create_adapter_env(
                adapter,
                env_name,
                env_size=env_size,
                seed=seed,
                max_steps=max_steps,
                answer_extractor=context.environment_extractor,
                make_kwargs=make_kwargs,
                extra_rewards=extra_rewards,
                invalid_action_text=getattr(context, "invalid_action_text", None),
                invalid_action_observation=getattr(
                    context, "invalid_action_observation", None
                ),
                advance_on_invalid=getattr(context, "advance_on_invalid", None),
            )
            gt_env = env
            gt_system_prompt = resolve_system_prompt(
                override_system_prompt=prediction_config.system_prompt,
                adapter=getattr(context, "adapter", None),
                prompting_scheme=getattr(context, "prompting_scheme", None),
                context_system_prompt_file=getattr(context, "system_prompt_file", None),
                adapter_system_prompt=env_system_prompt,
                fallback_system_prompt=dataset.metadata.get("system_prompt"),
                make_kwargs=make_kwargs,
                env_name=getattr(context, "env_name", None),
            )

            if not preload_exact_gt_resume:
                for est_config in config.estimations:
                    if est_config.assumption == SignalType.SHAPED_REWARD:
                        continue
                    gt_compatibility_by_name[est_config.name] = (
                        _gt_compatibility_metadata(
                            dataset_fingerprint,
                            points,
                            resume_descriptor=_build_gt_resume_descriptor(
                                est_config=est_config,
                                adapter=adapter,
                                env_name=env_name,
                                max_steps=max_steps,
                                make_kwargs=make_kwargs,
                                context=context,
                                prediction_config=prediction_config,
                                dataset_metadata=dataset.metadata,
                                turn_info=turn_info,
                                gt_environment_descriptor=gt_environment_descriptor,
                                gt_reward_signal_name=gt_reward_signal_name,
                                backends_config=backends_config,
                                step_penalty=step_penalty,
                                resolved_system_prompt=(
                                    None
                                    if est_config.policy_name is not None
                                    else gt_system_prompt
                                ),
                            ),
                        )
                    )

                existing_gt = _load_compatible_gt_predictions(
                    output_dir / "gt",
                    expected_gt_configs,
                    num_points=len(points),
                    compatibility_metadata_by_name=gt_compatibility_by_name,
                )
                for gt_name, pred in existing_gt.items():
                    gt_values[gt_name] = pred.values
                    raw_returns[gt_name] = []
                    gt_aborted[gt_name] = set()
                saved_gt_names = set(existing_gt.keys())

                gt_names_to_build = _gt_method_names_to_build(
                    expected_gt_names=set(expected_gt_configs),
                    existing_gt_names=set(existing_gt),
                    ranking_requested=ranking_requested,
                )

            # Multi-instance support for non-pure environments (e.g., Harbor)
            env_factory = None
            restore_fn = None
            if adapter == "harbor":
                harbor_kwargs = {"max_steps": max_steps} if max_steps else {}
                if make_kwargs:
                    harbor_kwargs.update(make_kwargs)
                if extra_rewards:
                    harbor_kwargs["extra_rewards"] = extra_rewards
                if context.environment_extractor is not None:
                    harbor_kwargs["answer_extractor"] = context.environment_extractor

                # Pre-flight diagnostics
                from qval.script_utils import check_harbor_environment

                preflight = check_harbor_environment(harbor_kwargs, env_name)
                exp_logger.log_event("harbor_preflight", preflight)

                from qval.script_utils import _apply_harbor_env_overrides

                effective_kwargs = _apply_harbor_env_overrides(dict(harbor_kwargs))
                effective_trials_dir = effective_kwargs.get(
                    "trials_dir", default_trials_dir
                )
                resource_watch_dirs = [effective_trials_dir]

                harbor_restore_mode = dataset.metadata.get(
                    "harbor_state_capture", "replay"
                )
                _validate_harbor_replay_configuration(
                    harbor_replay_cache=config.harbor_replay_cache,
                    adapter=adapter,
                    harbor_restore_mode=harbor_restore_mode,
                    make_kwargs=make_kwargs,
                )
                env_factory, restore_fn = create_harbor_env_factory(
                    env_name,
                    restore_mode=harbor_restore_mode,
                    artifact_root=str(resolved_dataset_path.parent),
                    **harbor_kwargs,
                )
                environment_type = harbor_kwargs.get("environment_type", "docker")
                is_apptainer = environment_type in ("apptainer-hpc", "singularity-hpc")
                if (
                    config.harbor_replay_cache
                    and harbor_restore_mode == "replay"
                    and is_apptainer
                ):
                    from qval.script_utils import ReplayCache

                    cache_dir = Path(effective_trials_dir) / "fs_restore_cache"
                    replay_cache = ReplayCache(cache_dir, env_name=env_name)
                    restore_fn = replay_cache.wrap(restore_fn)
                    logger.info("Harbor replay cache enabled: %s", cache_dir)

            elif adapter == "open_apps":
                open_apps_kwargs = {"max_steps": max_steps} if max_steps else {}
                if make_kwargs:
                    open_apps_kwargs.update(make_kwargs)
                if extra_rewards:
                    open_apps_kwargs["extra_rewards"] = extra_rewards
                env_factory, restore_fn = create_open_apps_env_factory(
                    env_name,
                    **open_apps_kwargs,
                )
            elif adapter == "gymnasium" and make_kwargs and make_kwargs.get("use_images"):
                # Vision gym envs (e.g., FL with pygame) can't pure_step,
                # so mid-trajectory rollouts need env_factory + restore_fn.
                from qval.script_utils import build_env_factory

                factory_result = build_env_factory(
                    adapter,
                    env_name,
                    dict(make_kwargs),
                    max_steps=max_steps,
                    extra_rewards=extra_rewards,
                    answer_extractor=context.environment_extractor,
                )
                env_factory = factory_result.env_factory
                restore_fn = factory_result.restore_fn
        else:
            logger.info(
                "All %d GT methods satisfied from existing predictions; skipping GT setup",
                len(existing_gt),
            )

    # Start resource monitoring after runtime-specific scratch paths are resolved.
    from qval.resource_monitor import ResourceMonitor

    resource_monitor = ResourceMonitor(watch_dirs=resource_watch_dirs)
    resource_monitor.start()

    try:
        if has_gt_configs:
            # Build GT methods
            try:
                for est_config in config.estimations:
                    if est_config.assumption == SignalType.SHAPED_REWARD:
                        logger.info(
                            "Skipping %s (SHAPED_REWARD, no MC GT)", est_config.name
                        )
                        continue
                    if est_config.name not in gt_names_to_build:
                        continue

                    policy_name = est_config.policy_name
                    resolved_backend_name: str | None
                    scripted_policy = policy_name is not None
                    scripted_metadata: dict[str, Any] | None = None
                    est_backend_config = None
                    est_prompt_budget = None
                    if scripted_policy:
                        scripted_metadata = _build_scripted_policy_metadata(
                            policy_name=policy_name,
                            make_kwargs=make_kwargs,
                            step_penalty=step_penalty,
                        )
                        est_backend, resolved_backend_name = get_scripted_policy(
                            policy_name,
                            make_kwargs,
                            step_penalty,
                        )
                        est_policy = Policy(
                            backend=est_backend,
                            sampling_params=SamplingParams(),
                            system_prompt=None,
                        )
                    else:
                        resolved_backend_name = resolve_backend_name(
                            est_config.backend_name
                            or prediction_config.gt_backend_name,
                            backends_config.backends,
                            backends_config.default_backend,
                        )
                        est_backend_config = backends_config.backends[
                            resolved_backend_name
                        ]
                        est_backend = get_backend(est_backend_config)
                        est_system_prompt = apply_cli_backend_tmux_prompt_hardening(
                            gt_system_prompt,
                            enabled=getattr(
                                prediction_config,
                                "cli_backend_tmux_prompt_hardening",
                                False,
                            ),
                            adapter=adapter,
                            make_kwargs=make_kwargs,
                            backend_config=est_backend_config,
                        )
                        est_policy = Policy(
                            backend=est_backend,
                            sampling_params=sampling_params_from_config(
                                est_backend_config.sampling,
                                backend_type=est_backend_config.type,
                                provider_preferences=est_backend_config.openrouter_provider,
                            ),
                            system_prompt=est_system_prompt,
                        )
                        # Try budget-aware truncation for this GT backend
                        if (
                            context.min_action_chars is not None
                            or context.min_observation_chars is not None
                            or context.min_current_observation_chars is not None
                        ):
                            from qval.token_budget import make_prompt_budget

                            est_prompt_budget = make_prompt_budget(
                                est_backend,
                                est_backend_config,
                                min_observation_chars=context.min_observation_chars,
                                min_action_chars=context.min_action_chars,
                                min_current_observation_chars=context.min_current_observation_chars,
                                max_history_turns=prediction_config.max_history_turns,
                            )
                    generation_descriptor = _build_gt_generation_descriptor(
                        environment=gt_environment_descriptor,
                        policy=_build_rollout_policy_descriptor(
                            backend_config=est_backend_config,
                            scripted_policy_name=policy_name,
                            scripted_metadata=scripted_metadata,
                        ),
                        prompt=_build_gt_prompt_descriptor(
                            system_prompt=est_policy.system_prompt,
                            turn_info=False if scripted_policy else turn_info,
                            min_action_chars=context.min_action_chars,
                            min_observation_chars=context.min_observation_chars,
                            prompt_budget=None
                            if scripted_policy
                            else est_prompt_budget,
                        ),
                    )
                    method = create_gt_method(
                        cast(Any, gt_env),
                        est_policy,
                        est_config,
                        est_config.assumption,
                        reward_signal_name=gt_reward_signal_name,
                        batch_size=config.batch_size,
                        turn_info=False if scripted_policy else turn_info,
                        discount_factor=config.discount_factor,
                        env_factory=env_factory,
                        restore_fn=restore_fn,
                        history_fn=None if scripted_policy else gt_history_fn,
                        prompt_budget=None if scripted_policy else est_prompt_budget,
                        format_reminder=None
                        if scripted_policy
                        else actor_format_reminder,
                        step_penalty=step_penalty,
                        generation_descriptor=generation_descriptor,
                    )
                    gt_methods_dict[est_config.name] = method

                gt_methods_to_run = {
                    name: method
                    for name, method in gt_methods_dict.items()
                    if name not in existing_gt
                }

                if gt_methods_to_run:
                    logger.info(
                        "Running GT estimation: %s (skipped %d already complete)",
                        list(gt_methods_to_run.keys()),
                        len(existing_gt),
                    )

                    saved_gt_names = set(existing_gt.keys())

                    def _on_gt_group_complete(
                        gt_name: str,
                        values: list[float],
                        raw: list,
                        aborted: set[int],
                    ) -> None:
                        est_cfg = next(
                            (e for e in config.estimations if e.name == gt_name),
                            None,
                        )
                        if est_cfg is None:
                            return
                        pred = Prediction(
                            method_name=gt_name,
                            method_type="gt",
                            values=values,
                            config=expected_gt_configs[gt_name],
                            metadata={
                                "backend_name": (
                                    est_cfg.policy_name
                                    if est_cfg.policy_name is not None
                                    else resolve_backend_name(
                                        est_cfg.backend_name
                                        or prediction_config.gt_backend_name,
                                        backends_config.backends,
                                        backends_config.default_backend,
                                    )
                                ),
                                "timestamp": datetime.now().astimezone().isoformat(),
                                **gt_compatibility_by_name[gt_name],
                            },
                        )
                        pred_path = _timestamped_prediction_path(
                            output_dir / "gt",
                            gt_name,
                        )
                        save_prediction(pred, pred_path)
                        logger.info(
                            "  Saved GT %s (incremental): %d values -> %s",
                            gt_name,
                            len(values),
                            pred_path,
                        )
                        saved_gt_names.add(gt_name)

                    new_gt_values, new_raw_returns, new_gt_aborted = collect_grouped_gt(
                        gt_methods_to_run,
                        points,
                        logger=exp_logger,
                        rollout_store_root=rollout_store_root,
                        dataset_fingerprint=dataset_fingerprint,
                        point_namespace="evaluation_points",
                        resume=persistence_config.resume,
                        trust_sibling_hash=persistence_config.trust_sibling_hash,
                        on_group_complete=_on_gt_group_complete,
                    )

                    gt_values.update(new_gt_values)
                    raw_returns.update(new_raw_returns)
                    gt_aborted.update(new_gt_aborted)

                    total_gt_aborted: set[int] = set()
                    for _gt_name, aborted_set in gt_aborted.items():
                        total_gt_aborted |= aborted_set
                    check_abort_threshold(
                        len(total_gt_aborted),
                        len(points),
                        config.max_aborted_points,
                        "GT estimation",
                    )

                    for gt_name, gt_values_list in new_gt_values.items():
                        if gt_name in saved_gt_names:
                            continue
                        est_config = next(
                            e for e in config.estimations if e.name == gt_name
                        )
                        pred = Prediction(
                            method_name=gt_name,
                            method_type="gt",
                            values=gt_values_list,
                            config=expected_gt_configs[gt_name],
                            metadata={
                                "backend_name": (
                                    est_config.policy_name
                                    if est_config.policy_name is not None
                                    else resolve_backend_name(
                                        est_config.backend_name
                                        or prediction_config.gt_backend_name,
                                        backends_config.backends,
                                        backends_config.default_backend,
                                    )
                                ),
                                "timestamp": datetime.now().astimezone().isoformat(),
                                **gt_compatibility_by_name[gt_name],
                            },
                        )
                        pred_path = _timestamped_prediction_path(
                            output_dir / "gt",
                            gt_name,
                        )
                        save_prediction(pred, pred_path)
                        logger.info(
                            "  Saved GT %s: %d values -> %s",
                            gt_name,
                            len(gt_values_list),
                            pred_path,
                        )

                    for gt_name in new_gt_values:
                        raw_rollouts = new_raw_returns.get(gt_name, [])
                        if raw_rollouts:
                            _log_rollout_summary_event(
                                exp_logger,
                                method_name=gt_name,
                                raw_rollouts=raw_rollouts,
                            )

                    # Log stats for GT estimation phases
                    for est_config in config.estimations:
                        if est_config.assumption == SignalType.SHAPED_REWARD:
                            continue
                        stats = compute_stats(exp_logger, f"gt:{est_config.name}")
                        if stats["total_generations"] > 0:
                            exp_logger.set_phase(f"gt:{est_config.name}")
                            exp_logger.log_event("stats", stats)
                            if stats["truncated_generations_pct"] > 10:
                                logger.warning(
                                    "High truncation rate for GT %s: %d/%d generations truncated (%.1f%%)",
                                    est_config.name,
                                    stats["truncated_generations"],
                                    stats["total_generations"],
                                    stats["truncated_generations_pct"],
                                )
            finally:
                if replay_cache is not None:
                    cache_stats = replay_cache.stats()
                    exp_logger.log_event("replay_cache_stats", cache_stats)
                    logger.info(
                        "Replay cache: %d fills, %d waiter restores, %d late hits, %d fallbacks",
                        cache_stats["fills"],
                        cache_stats["waiter_restores"],
                        cache_stats["late_hits"],
                        cache_stats["fallbacks"],
                    )
                    replay_cache.cleanup()

        # ── Eval methods ─────────────────────────────────────────────
        # Build eval method list: prefer config.eval_methods
        eval_method_configs: list[EvalMethodConfig] = []
        ranking_eval_configs: list[EvalMethodConfig] = []
        if config.eval_methods:
            eval_method_configs = list(config.eval_methods)

        if eval_method_configs:
            regular_eval_configs, ranking_eval_configs = _split_eval_method_configs(
                eval_method_configs
            )

            methods: dict[str, Any] = {}
            method_backend_names: dict[str, str | None] = {}
            method_configs_by_name: dict[str, EvalMethodConfig] = {}
            regular_deps = MethodBuildContext(
                context=context,
                backends_config=backends_config,
                get_backend=get_backend,
                eval_backend_name=prediction_config.eval_backend_name,
                default_max_history_turns=prediction_config.max_history_turns,
                step_penalty=step_penalty,
                discount_factor=config.discount_factor,
                batch_size=config.batch_size,
                env_context=env_context,
                dataset=dataset,
            )
            for mc in regular_eval_configs:
                method, method_backend_name = build_regular_method(
                    mc, regular_deps
                )
                methods[mc.name] = method
                method_backend_names[mc.name] = method_backend_name
                method_configs_by_name[mc.name] = mc

            if methods:
                include_actor_thinking = dataset.config.get(
                    "include_actor_thinking", False
                )
                display_points = prepare_display_points(points, include_actor_thinking)

                for method_name, method_fn in methods.items():
                    method_backend_name = method_backend_names.get(method_name)
                    method_config = method_configs_by_name[method_name]
                    num_samples = method_config.num_samples

                    if isinstance(method_fn, LLMCodeGenMethod) and num_samples > 1:
                        _run_multi_sample_codegen(
                            method_name=method_name,
                            method_fn=method_fn,
                            method_config=method_config,
                            method_backend_name=method_backend_name,
                            display_points=display_points,
                            prediction_config=prediction_config,
                            discount_factor=config.discount_factor,
                            max_aborted_points=config.max_aborted_points,
                            exp_logger=exp_logger,
                            output_dir=output_dir,
                        )
                    else:
                        exp_logger.set_phase(f"method:{method_name}")
                        logger.info("Evaluating %s...", method_name)
                        progress = exp_logger.make_progress_reporter(
                            name=f"Eval {method_name}",
                            logger_name=__name__,
                        )
                        try:
                            predicted = method_fn.evaluate_batch(
                                display_points,
                                progress_callback=progress,
                            )
                        except LogprobsNotReturnedError as exc:
                            logger.warning(
                                "Skipping method %s: backend logprobs unavailable "
                                "(backend=%s, model=%s): %s",
                                method_name,
                                exc.backend_name,
                                exc.model_name,
                                exc,
                            )
                            exp_logger.log_event(
                                "method_skipped",
                                {
                                    "method": method_name,
                                    "exception": "LogprobsNotReturnedError",
                                    "backend": exc.backend_name,
                                    "model": exc.model_name,
                                    "reason": str(exc),
                                },
                            )
                            continue
                        logger.info("  %s: %d predictions", method_name, len(predicted))

                        # Post-hoc codegen annotations
                        if isinstance(method_fn, (LLMCodeGenMethod, LLMEurekaMethod)):
                            annotate_codegen_records(exp_logger, method_name, method_fn)

                        pred = Prediction(
                            method_name=method_name,
                            method_type="eval",
                            values=predicted,
                            config=_build_eval_prediction_config(
                                backend_name=method_backend_name,
                                max_history_turns=_effective_method_max_history_turns(
                                    method_fn,
                                    prediction_config.max_history_turns,
                                ),
                                method_type=method_config.type,
                                policy_assumption=method_config.policy_assumption.name.lower(),
                                signal_type=method_config.signal_type.name.lower(),
                                discount_factor=config.discount_factor,
                                prompt_preset=method_config.prompt_preset,
                                prompt_batch_size=getattr(
                                    method_config, "prompt_batch_size", 1
                                ),
                                prompt_batch_mode=getattr(
                                    method_config, "prompt_batch_mode", "packed"
                                ),
                                num_verifications=getattr(
                                    method_config, "num_verifications", 1
                                ),
                                prompt_grouping=(
                                    "trajectory"
                                    if method_config.type == "llm_direct_gvl"
                                    else method_config.prompt_grouping
                                    if method_config.type == "llm_verifier"
                                    else None
                                ),
                                prompt_shuffle=(
                                    "deterministic_random"
                                    if method_config.type == "llm_direct_gvl"
                                    else None
                                ),
                                criteria=(
                                    method_config.criteria
                                    if method_config.type == "llm_verifier"
                                    else None
                                ),
                                score_scale=(
                                    "terminal_bench_letters_g20"
                                    if method_config.type == "llm_verifier"
                                    else None
                                ),
                                disclose_step_penalty=method_config.disclose_step_penalty,
                                disclose_discount_factor=method_config.disclose_discount_factor,
                                include_next_state=method_config.include_next_state,
                                search_iterations=(
                                    method_config.search_iterations
                                    if method_config.type == "llm_eureka"
                                    else None
                                ),
                                judge_num_points=(
                                    method_config.judge_num_points
                                    if method_config.type == "llm_eureka"
                                    else None
                                ),
                                seed=(
                                    method_config.seed
                                    if method_config.type == "baseline_random"
                                    else None
                                ),
                            ),
                            metadata={
                                "backend_name": method_backend_name,
                                "timestamp": datetime.now().astimezone().isoformat(),
                            },
                        )
                        # Include generated code for codegen methods
                        if (
                            isinstance(method_fn, (LLMCodeGenMethod, LLMEurekaMethod))
                            and method_fn.generated_code
                        ):
                            pred.metadata["generated_code"] = method_fn.generated_code

                        pred_path = _timestamped_prediction_path(
                            output_dir / "eval",
                            method_name,
                        )
                        save_prediction(pred, pred_path)
                        logger.info("  Saved eval %s -> %s", method_name, pred_path)

                        method_aborted = getattr(
                            method_fn, "last_aborted_indices", set()
                        )
                        check_abort_threshold(
                            len(method_aborted),
                            len(display_points),
                            config.max_aborted_points,
                            f"eval:{method_name}",
                        )

                        # Log truncation stats for this method
                        stats = compute_stats(exp_logger, f"method:{method_name}")
                        if stats["total_generations"] > 0:
                            exp_logger.log_event("stats", stats)
                            if stats["truncated_generations_pct"] > 10:
                                logger.warning(
                                    "High truncation rate for %s: %d/%d generations truncated (%.1f%%)",
                                    method_name,
                                    stats["truncated_generations"],
                                    stats["total_generations"],
                                    stats["truncated_generations_pct"],
                                )

        # ── Ranking predictions ────────────────────────────────────────
        ranking_points = getattr(dataset, "ranking_points", [])
        if config.max_eval_points is not None and ranking_points:
            allowed = {(p.trajectory_index, p.step_index) for p in points}
            total_rp = len(ranking_points)
            ranking_points = [
                rp
                for rp in ranking_points
                if (rp.trajectory_index, rp.step_index) in allowed
            ]
            logger.info(
                "Filtered ranking points to match eval subset: %d/%d",
                len(ranking_points),
                total_rp,
            )
        if ranking_eval_configs and not ranking_points:
            logger.error(
                "Ranking methods requested (%s) but dataset has no ranking_points. "
                "Enable collection.ranking_actions during dataset collection.",
                [mc.name for mc in ranking_eval_configs],
            )

        would_run_ranking = _should_run_ranking_predictions(
            ranking_points=ranking_points,
            ranking_eval_configs=ranking_eval_configs,
            estimation_configs=config.estimations,
        )
        if config.skip_ranking_predictions and would_run_ranking:
            logger.info(
                "Skipping ranking predictions (skip_ranking_predictions=True): "
                "%d ranking points in dataset were not processed.",
                len(ranking_points),
            )
        elif would_run_ranking:
            eval_q_lookup = _build_eval_q_lookup(
                gt_values,
                config.estimations,
                points,
            )
            _run_ranking_predictions(
                ranking_points=ranking_points,
                config=config,
                prediction_config=prediction_config,
                context=context,
                env_context=env_context,
                backends_config=backends_config,
                eval_method_configs=ranking_eval_configs,
                exp_logger=exp_logger,
                output_dir=output_dir,
                get_backend=get_backend,
                gt_env=gt_env,
                gt_methods_dict=gt_methods_dict,
                dataset=dataset,
                rollout_store_root=rollout_store_root,
                dataset_fingerprint=dataset_fingerprint,
                eval_q_lookup=eval_q_lookup,
                saved_ranking_gt_names=saved_ranking_gt_names,
            )

        elapsed = time.time() - start
        logger.info("Prediction complete in %.1fs", elapsed)

        # Stop resource monitor and log summary
        resource_summary = resource_monitor.stop()
        if resource_summary:
            exp_logger.log_event("resource_summary", resource_summary)

        # Save logs
        exp_logger.save_logs(log_path)
        logger.info("Logs saved to %s (%d records)", log_path, len(exp_logger.records))
    except BaseException:
        exc = sys.exc_info()[1]
        if _handle_pipeline_exception(
            exc,
            exp_logger=exp_logger,
            log_path=log_path,
            output_dir=output_dir,
            saved_gt_names=saved_gt_names,
            saved_ranking_gt_names=saved_ranking_gt_names,
        ):
            return
        raise
    finally:
        for cached_backend in backend_cache.values():
            try:
                cached_backend.close()
            except Exception as exc:
                logger.warning("Backend cleanup failed: %s", exc)


def _collect_ranking_gt(
    ranking_points: list[RankingPoint],
    gt_method: Any,
    aggregation: Any,
    *,
    rollout_store_root: Path | None,
    dataset_fingerprint: Any | None,
    resume: bool,
    trust_sibling_hash: bool = False,
    eval_q_lookup: dict[tuple[int, int], float] | None = None,
    progress_callback: Callable[[int, int], None] | None = None,
) -> tuple[list[float], set[int], int]:
    """Compute Q-values for all candidates across all ranking points.

    When *eval_q_lookup* is provided, ACTOR_PRIMARY candidates reuse the
    pre-computed eval-point Q-values and only alternative candidates are
    rolled out.  When *eval_q_lookup* is ``None``, all candidates
    (including ACTOR_PRIMARY) go through MC rollouts — identical to the
    previous behaviour.

    Returns the flat Q-values plus the aborted pseudo-point indices and the
    number of rollout-backed pseudo points that were attempted.
    """
    from qval.estimator import aggregate_returns
    from qval.types import RankingCandidateSource

    # Build pseudo-EvaluationPoints for candidates that need rollouts,
    # reusing eval Q-values for ACTOR_PRIMARY when available.
    result_slots: list[float | None] = []
    pseudo_points: list[EvaluationPoint] = []
    pseudo_point_keys: list[tuple[int, ...]] = []

    for rp in ranking_points:
        for cand_idx, candidate in enumerate(rp.candidates):
            key = (rp.trajectory_index, rp.step_index)
            if (
                eval_q_lookup is not None
                and candidate.source == RankingCandidateSource.ACTOR_PRIMARY
            ):
                if key not in eval_q_lookup:
                    raise ValueError(
                        f"Ranking point ({rp.trajectory_index}, {rp.step_index}) "
                        f"has no matching eval-point Q-value. This suggests the "
                        f"ranking points and evaluation points are misaligned."
                    )
                result_slots.append(eval_q_lookup[key])
            else:
                result_slots.append(None)
                pseudo_points.append(
                    EvaluationPoint(
                        state=rp.state,
                        action=candidate.action,
                        next_state=None,  # MC will step internally
                        trajectory_index=rp.trajectory_index,
                        step_index=rp.step_index,
                        extracted_action=candidate.extracted_action,
                        resolved_action=candidate.resolved_action,
                        history=rp.history,
                    )
                )
                pseudo_point_keys.append((rp.trajectory_index, rp.step_index, cand_idx))

    reused = sum(1 for v in result_slots if v is not None)
    if reused:
        logger.info(
            "Ranking GT: reused %d eval Q-values, %d alternative candidates to roll out",
            reused,
            len(pseudo_points),
        )

    if pseudo_points:
        _, raw_returns_map, ranking_gt_aborted = collect_grouped_gt(
            {"ranking": gt_method},
            pseudo_points,
            progress_callback=progress_callback,
            rollout_store_root=rollout_store_root,
            dataset_fingerprint=dataset_fingerprint,
            point_namespace="ranking_candidates",
            point_keys=pseudo_point_keys,
            resume=resume,
            trust_sibling_hash=trust_sibling_hash,
        )
        ranking_aborted_set = ranking_gt_aborted.get("ranking", set())
        estimates = aggregate_returns(raw_returns_map["ranking"], aggregation)
        rollout_values = [e.value for e in estimates]
    else:
        rollout_values = []
        ranking_aborted_set = set()

    # Merge reused and rollout values
    rollout_idx = 0
    final_values: list[float] = []
    for v in result_slots:
        if v is not None:
            final_values.append(v)
        else:
            final_values.append(rollout_values[rollout_idx])
            rollout_idx += 1

    return final_values, ranking_aborted_set, len(pseudo_points)


def _run_ranking_predictions(
    *,
    ranking_points: list[RankingPoint],
    config: Any,
    prediction_config: Any,
    context: Any,
    env_context: Any,
    backends_config: Any,
    eval_method_configs: list,
    exp_logger: ExperimentLogger,
    output_dir: Path,
    get_backend: Any,
    gt_env: Any,
    gt_methods_dict: dict,
    dataset: Any,
    rollout_store_root: Path,
    dataset_fingerprint: Any,
    eval_q_lookup: dict[str, dict[tuple[int, int], float]],
    saved_ranking_gt_names: set[str] | None = None,
) -> None:
    """Run ranking GT and eval predictions for ranking points."""

    logger.info("Processing %d ranking points", len(ranking_points))
    from qval.system_prompts import SCHEME_INSTRUCTIONS

    actor_scheme = getattr(context, "prompting_scheme", None) or "answer_tags"
    actor_format_reminder = SCHEME_INSTRUCTIONS.get(actor_scheme)
    gt_history_fn = _build_gt_history_fn(
        context, max_history_turns=prediction_config.max_history_turns
    )

    # ── Ranking GT ──────────────────────────────────────────────
    for est_config in config.estimations:
        if est_config.assumption == SignalType.SHAPED_REWARD:
            continue

        if gt_env is None:
            logger.warning(
                "No environment available for ranking GT estimation, skipping"
            )
            break

        # Build a GT method for Q(s,a) using the same env/policy setup
        # as regular GT, but forced to Q_VALUE signal type
        gt_name = f"ranking_gt_{est_config.name}"
        exp_logger.set_phase(f"gt:{gt_name}")
        logger.info("Computing ranking GT Q-values via %s...", est_config.name)

        # Reuse the existing GT method's policy if available, otherwise skip
        existing_method = gt_methods_dict.get(est_config.name)
        if existing_method is None:
            logger.warning(
                "GT method %s not found for ranking GT, skipping", est_config.name
            )
            continue

        from qval.mc_method import MCMethod
        from qval.mcts_method import MCTSMethod

        if not isinstance(existing_method, (MCMethod, MCTSMethod)):
            logger.warning(
                "Ranking GT requires MC/MCTS method, skipping %s", est_config.name
            )
            continue

        # Look up matching eval Q-values for ACTOR_PRIMARY reuse
        primary_q = eval_q_lookup.get(est_config.name)
        if primary_q is None:
            logger.warning(
                "Ranking GT for %s: no matching Q_VALUE eval GT found, "
                "computing all candidates from scratch (including ACTOR_PRIMARY)",
                est_config.name,
            )

        # Create Q-value GT method with same config but Q_VALUE signal type
        env_factory = getattr(existing_method, "_env_factory", None)
        restore_fn = getattr(existing_method, "_restore_fn", None)
        ranking_gt_rsn = context.reward_signal_name
        if config.step_penalty is not None:
            ranking_gt_rsn = None  # sum all signals when penalty active
        # Reuse prompt_budget from existing method's runner if available
        existing_prompt_budget = getattr(
            existing_method.runner,
            "prompt_budget",
            None,
        )
        q_method = create_gt_method(
            cast(Any, gt_env),
            existing_method.policy,
            est_config,
            SignalType.Q_VALUE,
            reward_signal_name=ranking_gt_rsn,
            batch_size=config.batch_size,
            turn_info=False
            if est_config.policy_name is not None
            else dataset.metadata.get("turn_info", False),
            discount_factor=config.discount_factor,
            env_factory=env_factory,
            restore_fn=restore_fn,
            history_fn=None if est_config.policy_name is not None else gt_history_fn,
            prompt_budget=None
            if est_config.policy_name is not None
            else existing_prompt_budget,
            format_reminder=None
            if est_config.policy_name is not None
            else actor_format_reminder,
            step_penalty=config.step_penalty,
            generation_descriptor=getattr(
                existing_method, "generation_descriptor", None
            ),
        )

        resolved_backend_name: str | None = None
        if est_config.policy_name is None and backends_config is not None:
            resolved_backend_name = resolve_backend_name(
                est_config.backend_name or prediction_config.gt_backend_name,
                backends_config.backends,
                backends_config.default_backend,
            )
        candidate_counts = _ranking_candidate_counts(ranking_points)
        pred_config = _build_ranking_gt_prediction_config(
            method=est_config.method,
            aggregation=est_config.aggregation.name.lower(),
            num_rollouts=est_config.num_rollouts,
            candidate_counts=candidate_counts,
            backend_name=resolved_backend_name,
            policy_name=est_config.policy_name,
            step_penalty=config.step_penalty,
            discount_factor=config.discount_factor,
        )
        ranking_generation_spec = None
        for spec_source in (q_method, existing_method):
            build_generation_spec = getattr(spec_source, "build_generation_spec", None)
            if build_generation_spec is None:
                continue
            try:
                ranking_generation_spec = build_generation_spec(
                    namespace="ranking_candidates",
                    primitive="state_action",
                    dataset_fingerprint=dataset_fingerprint,
                )
                break
            except (AttributeError, TypeError, ValueError):
                continue
        ranking_resume_descriptor = None
        if ranking_generation_spec is not None:
            ranking_resume_descriptor = _build_ranking_gt_resume_descriptor(
                generation=ranking_generation_spec,
                reward_signal_name=ranking_gt_rsn,
                discount_factor=config.discount_factor,
                step_penalty=config.step_penalty,
            )
        ranking_compatibility_metadata = _ranking_gt_compatibility_metadata(
            dataset_fingerprint,
            ranking_points,
            resume_descriptor=ranking_resume_descriptor,
        )
        ranking_coverage_metadata = _build_ranking_coverage_metadata(
            dataset_fingerprint,
            ranking_points,
        )
        existing_ranking_gt: dict[str, Prediction] = {}
        if ranking_resume_descriptor is not None:
            existing_ranking_gt = _load_compatible_ranking_gt_predictions(
                output_dir / "gt",
                {gt_name: pred_config},
                ranking_points=ranking_points,
                compatibility_metadata_by_name={
                    gt_name: ranking_compatibility_metadata,
                },
            )
        if gt_name in existing_ranking_gt:
            if saved_ranking_gt_names is not None:
                saved_ranking_gt_names.add(gt_name)
            logger.info(
                "Ranking GT %s satisfied from existing prediction; skipping recompute",
                gt_name,
            )
            continue

        ranking_gt_result = _collect_ranking_gt(
            ranking_points,
            q_method,
            est_config.aggregation,
            rollout_store_root=rollout_store_root,
            dataset_fingerprint=dataset_fingerprint,
            resume=config.mc_rollout_persistence.resume,
            trust_sibling_hash=config.mc_rollout_persistence.trust_sibling_hash,
            eval_q_lookup=primary_q,
            progress_callback=exp_logger.make_progress_reporter(
                name=f"Ranking GT {est_config.name} rollouts",
                logger_name=__name__,
            ),
        )
        q_values, ranking_aborted_set, ranking_rollout_count = ranking_gt_result

        pred = Prediction(
            method_name=gt_name,
            method_type="gt",
            values=q_values,
            config=pred_config,
            metadata={
                "timestamp": datetime.now().astimezone().isoformat(),
                **ranking_coverage_metadata,
                **ranking_compatibility_metadata,
            },
        )
        pred_path = _timestamped_prediction_path(
            output_dir / "gt",
            gt_name,
        )
        save_prediction(pred, pred_path)
        if saved_ranking_gt_names is not None:
            saved_ranking_gt_names.add(gt_name)
        logger.info(
            "  Saved ranking GT %s: %d Q-values -> %s",
            gt_name,
            len(q_values),
            pred_path,
        )
        check_abort_threshold(
            len(ranking_aborted_set),
            ranking_rollout_count,
            config.max_aborted_points,
            "ranking GT",
        )

    # ── Ranking eval methods ────────────────────────────────────
    if eval_method_configs:
        ranking_deps = MethodBuildContext(
            context=context,
            backends_config=backends_config,
            get_backend=get_backend,
            eval_backend_name=prediction_config.eval_backend_name,
            default_max_history_turns=prediction_config.max_history_turns,
            step_penalty=config.step_penalty,
            discount_factor=config.discount_factor,
            batch_size=config.batch_size,
            env_context=env_context,
            dataset=dataset,
        )
        for mc in eval_method_configs:
            ranking_method, method_backend_name = build_ranking_method(
                mc, ranking_deps
            )

            exp_logger.set_phase(f"method:{mc.name}")
            progress = exp_logger.make_progress_reporter(
                name=f"Eval {mc.name}",
                logger_name=__name__,
            )
            candidate_counts = _ranking_candidate_counts(ranking_points)
            ranking_coverage_metadata = _build_ranking_coverage_metadata(
                dataset_fingerprint,
                ranking_points,
            )
            method_metadata: dict[str, Any] = {}

            if mc.type == "llm_ranking":
                logger.info("Ranking eval: %s...", mc.name)
                rankings = ranking_method.rank_batch(
                    ranking_points,
                    progress_callback=progress,
                )
                pred_values = _flatten_rankings_to_ranks(
                    rankings=rankings,
                    ranking_points=ranking_points,
                )
                prediction_format = "ranking_predicted"
            elif mc.type == "sdpo_ranking":
                logger.info("SDPO ranking eval: %s...", mc.name)
                point_scores = ranking_method.score_batch(
                    ranking_points,
                    progress_callback=progress,
                )
                pred_values = [
                    float(score) for scores in point_scores for score in scores
                ]
                prediction_format = "ranking_scores"
                method_metadata["score_formula"] = (
                    "mean_token_logprob_delta_teacher_minus_student"
                )
                if mc.max_feedback_chars is not None:
                    method_metadata["max_feedback_chars"] = mc.max_feedback_chars
            elif mc.type == "sdpo_short_expert_continuation":
                logger.info("SDPO-GT next-step summary eval: %s...", mc.name)
                point_scores = ranking_method.score_batch(
                    ranking_points,
                    progress_callback=progress,
                )
                pred_values = [
                    float(score) for scores in point_scores for score in scores
                ]
                prediction_format = "ranking_scores"
                method_metadata["score_formula"] = (
                    "mean_token_logprob_delta_teacher_with_next_expert_step_summary_minus_student"
                )
                method_metadata["teacher_feedback"] = (
                    "next_state_plus_next_expert_step_and_rollout_summary"
                )
                method_metadata["expert_rollout_store"] = mc.expert_rollout_store
                method_metadata["max_expert_continuation_steps"] = (
                    mc.max_expert_continuation_steps
                )
            elif mc.type == "delta_belief_ranking":
                logger.info("Delta belief ranking eval: %s...", mc.name)
                point_scores = ranking_method.score_batch(
                    ranking_points,
                    progress_callback=progress,
                )
                pred_values = [
                    float(score) for scores in point_scores for score in scores
                ]
                prediction_format = "ranking_scores"
                method_metadata["score_formula"] = "log_p_success_post_minus_pre"
                method_metadata["positive_verbalizers"] = list(
                    ranking_method.positive_verbalizers
                )
                method_metadata["negative_verbalizers"] = list(
                    ranking_method.negative_verbalizers
                )
            else:
                raise ValueError(f"Unsupported ranking eval method type: {mc.type!r}")

            ranking_pred_config = {
                "prediction_format": prediction_format,
                "candidate_counts": candidate_counts,
                "total_candidates": sum(candidate_counts),
                "backend_name": method_backend_name,
                "max_history_turns": prediction_config.max_history_turns,
                "method_type": mc.type,
                "policy_assumption": mc.policy_assumption.name.lower(),
                "signal_type": SignalType.Q_VALUE.name.lower(),
                "discount_factor": config.discount_factor,
                "prompt_preset": mc.prompt_preset,
                "disclose_step_penalty": mc.disclose_step_penalty,
                "disclose_discount_factor": mc.disclose_discount_factor,
                "include_next_state": mc.include_next_state,
            }
            if mc.type == "sdpo_short_expert_continuation":
                ranking_pred_config["expert_rollout_store"] = mc.expert_rollout_store
                ranking_pred_config["max_expert_continuation_steps"] = (
                    mc.max_expert_continuation_steps
                )
            output_method_name = (
                _SDPO_SHORT_EXPERT_CONTINUATION_EVAL_NAME
                if mc.type == "sdpo_short_expert_continuation"
                else mc.name
            )
            output_prefix = (
                f"eval_{output_method_name}"
                if mc.type == "sdpo_short_expert_continuation"
                else f"eval_{mc.name}"
            )

            pred = Prediction(
                method_name=output_method_name,
                method_type="eval",
                values=pred_values,
                config=ranking_pred_config,
                metadata={
                    "backend_name": method_backend_name,
                    "timestamp": datetime.now().astimezone().isoformat(),
                    **ranking_coverage_metadata,
                    **method_metadata,
                },
            )
            pred_path = _timestamped_prediction_path(
                output_dir / "eval",
                output_prefix,
            )
            save_prediction(pred, pred_path)
            logger.info("  Saved ranking eval %s -> %s", output_method_name, pred_path)

            ranking_aborted = getattr(ranking_method, "last_aborted_indices", set())
            check_abort_threshold(
                len(ranking_aborted),
                len(ranking_points),
                config.max_aborted_points,
                f"eval:{mc.name}",
            )

            stats = compute_stats(exp_logger, f"method:{mc.name}")
            if stats["total_generations"] > 0:
                exp_logger.log_event("stats", stats)


def _codegen_canonical_token(method_name: str, token: str) -> str:
    """Insert ``token`` before the trailing ``_qv``/``_sv`` signal-type suffix.

    e.g. ``codegen_qv`` + ``s3`` -> ``codegen-s3_qv``;
         ``codegen_qv`` + ``mean`` -> ``codegen-mean_qv``.

    The method registry's canonical codegen forms are
    ``codegen-s<N>_(qv|sv)`` and ``codegen-mean_(qv|sv)`` — the suffix is
    the signal-type tag and stays at the end. ``method_name`` must already
    end with ``_qv`` or ``_sv``.
    """
    for suffix in ("_qv", "_sv"):
        if method_name.endswith(suffix):
            return f"{method_name[:-3]}-{token}{suffix}"
    raise ValueError(
        f"codegen method_name {method_name!r} must end with '_qv' or '_sv' "
        "to generate canonical sample/mean names"
    )


def _run_multi_sample_codegen(
    *,
    method_name: str,
    method_fn: LLMCodeGenMethod,
    method_config: Any,
    method_backend_name: str | None,
    display_points: list,
    prediction_config: Any,
    discount_factor: float,
    max_aborted_points: float,
    exp_logger: ExperimentLogger,
    output_dir: Path,
) -> None:
    """Run multi-sample code generation for a single LLMCodeGenMethod."""
    num_samples = method_config.num_samples
    exp_logger.set_phase(f"method:{method_name}")
    logger.info("Generating %d code samples for %s...", num_samples, method_name)

    # Warn about temperature=0 with multiple samples
    if method_fn._sampling_params.temperature == 0.0 and num_samples > 1:
        logger.warning(
            "temperature=0 with num_samples=%d for %s — all samples "
            "will likely be identical",
            num_samples,
            method_name,
        )

    samples = method_fn.generate_samples(num_samples)
    compiled_count = sum(1 for sample in samples if sample is not None)
    logger.info(
        "  %s: %d/%d samples compiled successfully",
        method_name,
        compiled_count,
        num_samples,
    )

    num_fully_aborted_samples = 0
    sample_values: list[list[float]] = []
    for i, sample in enumerate(samples):
        sample_name = _codegen_canonical_token(method_name, f"s{i}")
        exp_logger.set_phase(f"method:{sample_name}")

        if sample is None:
            logger.warning(
                "  Sample %d/%d (%s) aborted during code generation",
                i + 1,
                num_samples,
                sample_name,
            )
            predicted = [math.nan] * len(display_points)
            num_fully_aborted_samples += 1
        else:
            logger.info(
                "  Evaluating sample %d/%d (%s)...", i + 1, num_samples, sample_name
            )
            progress = exp_logger.make_progress_reporter(
                name=f"Eval {sample_name}",
                logger_name=__name__,
            )
            predicted = method_fn.evaluate_batch_with_fn(
                display_points, sample.signal_fn, progress_callback=progress
            )
            logger.info("    %s: %d predictions", sample_name, len(predicted))
        sample_values.append(predicted)

        pred_config = _build_eval_prediction_config(
            backend_name=method_backend_name,
            max_history_turns=_effective_method_max_history_turns(
                method_fn,
                prediction_config.max_history_turns,
            ),
            method_type=method_config.type,
            policy_assumption=method_config.policy_assumption.name.lower(),
            signal_type=method_config.signal_type.name.lower(),
            discount_factor=discount_factor,
            prompt_preset=method_config.prompt_preset,
            prompt_batch_size=getattr(method_config, "prompt_batch_size", 1),
            prompt_batch_mode=getattr(method_config, "prompt_batch_mode", "packed"),
            num_verifications=getattr(method_config, "num_verifications", 1),
            disclose_step_penalty=method_config.disclose_step_penalty,
            disclose_discount_factor=method_config.disclose_discount_factor,
            include_next_state=method_config.include_next_state,
        )
        pred_config["sample_index"] = i
        pred_config["sample_group"] = method_name
        pred_config["num_samples"] = num_samples

        pred = Prediction(
            method_name=sample_name,
            method_type="eval",
            values=predicted,
            config=pred_config,
            metadata={
                "backend_name": method_backend_name,
                "timestamp": datetime.now().astimezone().isoformat(),
            },
        )
        if sample is None:
            pred.metadata["generation_aborted"] = True
        else:
            pred.metadata["generated_code"] = sample.code
        pred_path = _timestamped_prediction_path(
            output_dir / "eval",
            sample_name,
        )
        save_prediction(pred, pred_path)
        logger.info("    Saved eval %s -> %s", sample_name, pred_path)

    # Save a standalone mean-of-predictions artifact. Per-point NaN-skip:
    # samples that returned NaN at a given point (runtime error on that
    # input, or fully-aborted sample) contribute nothing to that point's
    # mean. When all samples are NaN at a point, the mean is NaN there and
    # compute_correlation drops the point. No ``sample_group`` tag: this
    # lands in the summary as its own eval method row instead of being
    # folded into the per-sample aggregate statistics.
    total_points = len(display_points)
    per_point_sum = [0.0] * total_points
    per_point_count = [0] * total_points
    for values in sample_values:
        for idx, value in enumerate(values):
            if not math.isnan(value):
                per_point_sum[idx] += value
                per_point_count[idx] += 1
    mean_values = [
        per_point_sum[idx] / per_point_count[idx]
        if per_point_count[idx] > 0
        else math.nan
        for idx in range(total_points)
    ]

    mean_pred_config = _build_eval_prediction_config(
        backend_name=method_backend_name,
        max_history_turns=_effective_method_max_history_turns(
            method_fn,
            prediction_config.max_history_turns,
        ),
        method_type=method_config.type,
        policy_assumption=method_config.policy_assumption.name.lower(),
        signal_type=method_config.signal_type.name.lower(),
        discount_factor=discount_factor,
        prompt_preset=method_config.prompt_preset,
        prompt_batch_size=getattr(method_config, "prompt_batch_size", 1),
        prompt_batch_mode=getattr(method_config, "prompt_batch_mode", "packed"),
        num_verifications=getattr(method_config, "num_verifications", 1),
        disclose_step_penalty=method_config.disclose_step_penalty,
        disclose_discount_factor=method_config.disclose_discount_factor,
        include_next_state=method_config.include_next_state,
    )
    mean_name = _codegen_canonical_token(method_name, "mean")
    mean_pred = Prediction(
        method_name=mean_name,
        method_type="eval",
        values=mean_values,
        config=mean_pred_config,
        metadata={
            "backend_name": method_backend_name,
            "timestamp": datetime.now().astimezone().isoformat(),
            "aggregated_from_samples": num_samples,
            "per_point_valid_counts": per_point_count,
        },
    )
    mean_path = _timestamped_prediction_path(
        output_dir / "eval",
        mean_name,
    )
    save_prediction(mean_pred, mean_path)
    logger.info("    Saved eval %s -> %s", mean_name, mean_path)

    # Aggregated abort check: for multi-sample codegen the failure
    # granularity is the sample, not the point, so we compare the
    # share of fully-aborted samples against max_aborted_points once
    # across the whole set instead of per-sample. This lets a single
    # bad sample coexist with N-1 good siblings while still catching
    # systemic failure (e.g. the model cannot produce runnable code).
    if num_samples > 0 and num_fully_aborted_samples / num_samples > max_aborted_points:
        raise RuntimeError(
            f"{num_fully_aborted_samples}/{num_samples} codegen samples "
            f"for '{method_name}' failed to generate runnable code "
            f"(> max_aborted_points={max_aborted_points:.1%})."
        )

    # Log truncation stats for the generation phase
    stats = compute_stats(exp_logger, f"method:{method_name}")
    if stats["total_generations"] > 0:
        exp_logger.log_event("stats", stats)
        if stats["truncated_generations_pct"] > 10:
            logger.warning(
                "High truncation rate for %s: %d/%d generations truncated (%.1f%%)",
                method_name,
                stats["truncated_generations"],
                stats["total_generations"],
                stats["truncated_generations_pct"],
            )


def _validate_harbor_replay_configuration(
    *,
    harbor_replay_cache: bool,
    adapter: str,
    harbor_restore_mode: str | None,
    make_kwargs: dict[str, Any] | None,
) -> None:
    """Reject incompatible Harbor replay-cache configurations."""
