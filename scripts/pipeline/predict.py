"""Step 2: Generate predictions — GT estimation and eval methods.

Loads a Dataset pickle, runs GT methods (MC/MCTS rollouts) and/or
evaluation methods (LLM-based), and saves per-method prediction JSON files.

What to run — GT actors, eval methods, and the backends each uses — is declared
in the prediction YAML config; there are no per-method or per-backend CLI flags.
Configs are normally generated by ``scripts/generate_configs.py`` into
``catalogs/<name>/configs/prediction/<env>/``. They resolve shared inputs
(dataset, env contexts, ``backends.yaml``) under ``shared/`` and write outputs
under the catalog.

Usage:
    python scripts/pipeline/predict.py \
        --config catalogs/qval_benchmark/configs/prediction/frozen_lake/100pt_8x8_g4-26-or_text.yaml

Options:
    --dataset PATH               Override the dataset pickle named in the config.
    --output-dir PATH            Override the prediction output directory.
    --tensor-parallel-size N     Override tensor_parallel_size for all vLLM
                                 backends (e.g. from the SLURM GPU count).
    --max-aborted-points FLOAT   Abort if the fraction of backend-aborted points
                                 exceeds this threshold (default: 0.1).
    --max-eval-points N          Use at most the first N evaluation points.
"""

